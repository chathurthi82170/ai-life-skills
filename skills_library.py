def adapt_steps_for_age(raw_steps, age):
    """Adapts step length and complexity according to student age."""
    if not raw_steps or not isinstance(raw_steps, list):
        return raw_steps
    
    try:
        age_num = int(age)
    except Exception:
        age_num = 12

    if age_num <= 8:
        # Junior Mode (Age 3-8): 3-4 simple visual steps
        if len(raw_steps) > 4:
            adapted = [raw_steps[0], raw_steps[len(raw_steps)//3], raw_steps[(len(raw_steps)*2)//3], raw_steps[-1]]
        else:
            adapted = list(raw_steps)
        return adapted
    
    elif age_num <= 13:
        # Middle Mode (Age 9-13): 5-6 practical steps
        if len(raw_steps) > 6:
            adapted = raw_steps[:5] + [raw_steps[-1]]
        else:
            adapted = list(raw_steps)
        return adapted
        
    else:
        # Senior Mode (Age 14-25): Full 6-8 independent real-world steps
        return list(raw_steps)
